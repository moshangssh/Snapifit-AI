export const DEFAULT_EXPERT_ID = "general"

export function getExpertRole(id: string | undefined): ExpertRole {
  return (
    EXPERT_ROLES.find((expert) => expert.id === id) ??
    (EXPERT_ROLES.find((expert) => expert.id === DEFAULT_EXPERT_ID) as ExpertRole)
  )
}

/** expertId → 专家显示名(团队记忆渲染等),未知 id 原样返回。 */
export function expertDisplayName(id: string): string {
  return EXPERT_ROLES.find((expert) => expert.id === id)?.name ?? id
}
